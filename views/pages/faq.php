  <h1>FAQ</h1>
  <div class="faq">
    <details open><summary>Что такое белый IP vs NAT?</summary>
      <p>Белый (публичный) IP назначается серверу и доступен из интернета напрямую. NAT — общий адрес хостера с пробросом портов. Мы продаём лоты с публичными адресами из российских подсетей.</p>
    </details>
    <details><summary>Чем аренда отличается от выкупа?</summary>
      <p>Аренда — оплата за месяц использования. Рассрочка — фиксированная сумма на 2 или 4 недели. Выкуп «навсегда» — разовая оплата лота без помесячной платы магазину (условия хостера уточняйте в описании).</p>
    </details>
    <details id="check-ip"><summary>Как проверить IP?</summary>
      <p>На карточке указана подсеть. Перед выдачей мы проверяем доступность адреса. Вы можете провести свою проверку после получения IP в кабинете.</p>
    </details>
    <details><summary>Что если подсеть перестала проходить проверку?</summary>
      <p>Создайте тикет «IP не проходит проверку». Рассмотрим замену по регламенту при наличии свободного ресурса.</p>
    </details>
    <details><summary>Какие данные выдаются после оплаты?</summary>
      <p>IP, hostname, ссылка на панель (если есть), логин. Секретные данные скрыты по умолчанию — кнопка «Показать» в кабинете.</p>
    </details>
    <details><summary>Это VPN-панель?</summary>
      <p>Нет. WL Sales — магазин серверов/VPS с публичным IP. Мы не выдаём VPN-конфиги, ключи подписок и не встраиваем Xray.</p>
    </details>
  </div>
</section>
